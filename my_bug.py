# Часть 1. Багованный код (7 строк)
days = ("Пн", "Ср", "Пт")
workouts = dict.fromkeys(days, [])

workouts["Пн"].append("Бег 5 км")
workouts["Ср"].append("Бассейн")

for day, tasks in workouts.items():
    print(f"[Баг] {day}: {tasks}")

# Часть 2. Комментарий (что происходит и почему)
# Метод dict.fromkeys(days, []) не создаёт новый список для каждого ключа, а присваивает всем ключам ссылку на один и тот же изменяемый объект списка в памяти (скрытый алиасинг).
# Поэтому вызов .append() для "Пн" и "Ср" мутирует этот общий список, и все три дня недели (включая "Пт", куда ничего не добавляли) начинают отображать одинаковый набор тренировок.
# Чтобы у каждого ключа был собственный независимый список, нужно создавать новый объект [] на каждой итерации с помощью словарного включения (dict comprehension).

# Часть 3. Исправленная версия
days = ("Пн", "Ср", "Пт")
workouts = {day: [] for day in days}

workouts["Пн"].append("Бег 5 км")
workouts["Ср"].append("Бассейн")

for day, tasks in workouts.items():
    print(f"[Ок]  {day}: {tasks}")